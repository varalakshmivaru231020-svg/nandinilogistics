import { notFound } from "next/navigation";

import { requirePermission } from "@/lib/rbac/guard";
import { prisma } from "@/lib/db";
import { PERM } from "@/lib/permissions/codes";
import { formatDate, money, qty } from "@/lib/utils";
import { requirePrintProjectAccess } from "@/components/print/access";
import { AmountInWords, FactList, PrintBanner, PrintBox, SectionLabel, SignatureBlocks } from "@/components/print/blocks";
import { chargeLineTotal, discountState, quoteExpired, taxByRate } from "@/components/print/figures";
import { LETTERHEAD_COMPANY_SELECT, Letterhead } from "@/components/print/letterhead";
import { PrintSheet } from "@/components/print/print-sheet";

/**
 * The printable cost sheet. Every figure is the one stored when the sheet was
 * generated by `buildCostSheet()` — nothing is re-derived here except line
 * totals and the GST summary, the same way the cost sheet screen shows them.
 * Scoped through the unit's project; the lead's contact details never print.
 */

export async function generateMetadata({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const s = await prisma.costSheet.findUnique({ where: { id }, select: { costSheetNo: true } });
  return { title: s ? `Print ${s.costSheetNo}` : "Cost Sheet" };
}

export default async function PrintCostSheetPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const ctx = await requirePermission(PERM.sales.costSheet.view, PERM.sales.costSheet.print);

  const sheet = await prisma.costSheet.findUnique({
    where: { id },
    include: {
      unit: {
        select: {
          unitNumber: true, floorNumber: true, superBuiltUpArea: true, builtUpArea: true, carpetArea: true,
          parkingSlots: true, plcTag: true, facing: true, projectId: true,
          block: { select: { name: true } },
          unitType: { select: { name: true } },
          project: { select: { code: true, name: true, reraNumber: true, company: { select: LETTERHEAD_COMPANY_SELECT } } },
        },
      },
      lead: { select: { name: true, leadNo: true } },
      lines: { orderBy: { sortOrder: "asc" } },
      bookings: { select: { bookingNo: true, status: true } },
    },
  });
  if (!sheet) notFound();

  requirePrintProjectAccess(ctx, sheet.unit.projectId);

  const people = await prisma.user.findMany({
    where: { id: { in: [sheet.createdById, sheet.discountApprovedById].filter((v): v is string => Boolean(v)) } },
    select: { id: true, name: true },
  });
  const nameOf = (userId: string | null) => (userId ? people.find((p) => p.id === userId)?.name ?? null : null);

  // Read once, during data fetching — the same instant decides "expired" everywhere on the sheet.
  const nowMs = new Date().getTime();
  const { unit } = sheet;
  const company = unit.project.company;
  const booking = sheet.bookings.find((b) => b.status !== "CANCELLED") ?? null;
  const discount = discountState(Number(sheet.discountAmount), sheet.discountApprovedAt);
  const expired = quoteExpired(sheet.validUntil, booking !== null, nowMs);
  const lines = sheet.lines.map((l) => ({
    id: l.id,
    label: l.label,
    quantity: Number(l.quantity),
    rate: Number(l.rate),
    amount: Number(l.amount),
    taxPct: Number(l.taxPct),
    taxAmount: Number(l.taxAmount),
  }));
  const gst = taxByRate(lines);
  const status = booking ? `Booked (${booking.bookingNo})` : expired ? "Expired" : "Quoted";

  return (
    <PrintSheet backHref={`/sales/cost-sheets/${sheet.id}`} backLabel={sheet.costSheetNo} printLabel="Print cost sheet">
      <Letterhead
        company={company}
        title="COST SHEET"
        facts={[
          { label: "Cost sheet No.", value: sheet.costSheetNo, emphasis: "bold" },
          { label: "Generated", value: formatDate(sheet.createdAt) },
          { label: "Valid until", value: formatDate(sheet.validUntil) },
          { label: "Status", value: status, emphasis: "semibold" },
        ]}
      />

      {discount === "pending" && (
        <PrintBanner tone="warn">Discount awaiting approval — figures are not final</PrintBanner>
      )}
      {expired && <PrintBanner tone="bad">Quote expired on {formatDate(sheet.validUntil)}</PrintBanner>}

      <section className="print-keep mt-4 grid grid-cols-2 gap-4">
        <PrintBox label="Unit">
          <p className="mt-1 text-[13px] font-bold">
            Unit {unit.unitNumber}{unit.block ? ` · ${unit.block.name}` : ""}
          </p>
          <p className="text-[10.5px] text-muted-600">{unit.project.code} — {unit.project.name}</p>
          <FactList
            rows={[
              ["Type", unit.unitType?.name ?? "—"],
              ["Floor", String(unit.floorNumber)],
              ["Super built-up", `${qty(unit.superBuiltUpArea, 2)} sq.ft`],
              ["Carpet", `${qty(unit.carpetArea, 2)} sq.ft`],
              unit.facing ? ["Facing", unit.facing] : false,
              ["Parking", String(unit.parkingSlots)],
              unit.plcTag ? ["PLC", unit.plcTag.replace(/_/g, " ")] : false,
              unit.project.reraNumber ? ["RERA", unit.project.reraNumber] : false,
            ]}
          />
        </PrintBox>

        <PrintBox label="Prepared for">
          <p className="mt-1 text-[13px] font-bold">{sheet.lead?.name ?? "—"}</p>
          {sheet.lead && <p className="text-[10.5px] text-muted-600">Lead {sheet.lead.leadNo}</p>}
          <FactList
            rows={[
              ["Base rate", `${money(sheet.baseRate, true)} / sq.ft`],
              ["Generated", formatDate(sheet.createdAt)],
              ["Valid until", formatDate(sheet.validUntil)],
              ["Prepared by", nameOf(sheet.createdById) ?? "—"],
            ]}
          />
        </PrintBox>
      </section>

      <section className="mt-4">
        <table>
          <thead>
            <tr>
              <th className="w-8 text-right">#</th>
              <th className="text-left">Charge</th>
              <th className="text-right">Qty</th>
              <th className="text-right">Rate</th>
              <th className="text-right">Amount</th>
              <th className="text-right">GST</th>
              <th className="text-right">Line total</th>
            </tr>
          </thead>
          <tbody>
            {lines.map((l, i) => (
              <tr key={l.id}>
                <td className="num text-right">{i + 1}</td>
                <td>{l.label}</td>
                <td className="num text-right">{qty(l.quantity, 2)}</td>
                <td className="num text-right">{money(l.rate, true)}</td>
                <td className="num text-right">{money(l.amount, true)}</td>
                <td className="num text-right">{l.taxPct > 0 ? `${money(l.taxAmount, true)} (${l.taxPct}%)` : "—"}</td>
                <td className="num text-right">{money(chargeLineTotal(l), true)}</td>
              </tr>
            ))}
          </tbody>
        </table>

        <div className="print-keep mt-2 flex items-start justify-between gap-6">
          <div className="max-w-[55%] space-y-2 pt-1">
            <AmountInWords amount={Number(sheet.totalAmount)} />
            {gst.length > 0 && (
              <table className="!w-auto text-[10.5px] [&_td]:!py-0.5">
                <thead>
                  <tr><th className="text-left">GST rate</th><th className="text-right">Taxable</th><th className="text-right">GST</th></tr>
                </thead>
                <tbody>
                  {gst.map((g) => (
                    <tr key={g.rate}>
                      <td>{g.rate}%</td>
                      <td className="num text-right">{money(g.taxable, true)}</td>
                      <td className="num text-right">{money(g.tax, true)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </div>
          <table className="!w-72 [&_td]:!py-1">
            <tbody>
              <tr><td className="text-muted-600">Sub-total</td><td className="num text-right">{money(sheet.subTotal, true)}</td></tr>
              <tr><td className="text-muted-600">GST</td><td className="num text-right">{money(sheet.taxAmount, true)}</td></tr>
              {discount !== "none" && (
                <tr>
                  <td className="text-muted-600">
                    Discount
                    <span className="block text-[9.5px]">
                      {discount === "approved"
                        ? `Approved ${formatDate(sheet.discountApprovedAt)}${nameOf(sheet.discountApprovedById) ? ` by ${nameOf(sheet.discountApprovedById)}` : ""}`
                        : "Pending approval"}
                    </span>
                  </td>
                  <td className="num text-right">−{money(sheet.discountAmount, true)}</td>
                </tr>
              )}
              <tr className="font-bold">
                <td>Total</td><td className="num text-right text-[13px]">{money(sheet.totalAmount, true)}</td>
              </tr>
            </tbody>
          </table>
        </div>
      </section>

      <section className="print-keep mt-5 rounded border border-line-400 p-3 text-[10.5px]">
        <SectionLabel>Please note</SectionLabel>
        <p className="mt-1">
          This cost sheet is an estimate for information only and is <span className="font-semibold">not an offer</span>{" "}
          until the unit is booked. Prices, charges and taxes are as on the date generated and hold only until the validity
          date; the unit is not reserved by this sheet. Stamp duty, registration and statutory levies revised by the
          government are payable at actuals.
        </p>
      </section>

      <SignatureBlocks
        blocks={[
          { role: "Prepared by", name: nameOf(sheet.createdById) ?? "" },
          { role: "Customer acknowledgement", name: sheet.lead?.name ?? "" },
        ]}
      />
    </PrintSheet>
  );
}
