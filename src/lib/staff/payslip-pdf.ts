import "server-only";

import PDFDocument from "pdfkit";

import { monthLabel } from "./payslip";

/**
 * The payslip as a one-page PDF — the SOW's "manual payslip generation per
 * staff (PDF)". Built from the stored figures, so the file says exactly what
 * the record says.
 */
export interface PayslipPdfInput {
  employeeCode: string;
  name: string;
  designation: string | null;
  month: string;
  payableDays: number | null;
  gross: number;
  advance: number;
  deductions: number;
  netPay: number;
  notes: string | null;
  generatedBy: string;
  generatedAt: Date;
}

const rupees = (v: number) => `Rs. ${v.toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

export async function toPayslipPdf(input: PayslipPdfInput): Promise<Buffer> {
  const doc = new PDFDocument({
    size: "A4",
    margin: 48,
    info: { Title: `Payslip ${input.employeeCode} ${input.month}`, Author: "Nandini Logistics", CreationDate: input.generatedAt },
  });
  const chunks: Buffer[] = [];
  const done = new Promise<Buffer>((resolve, reject) => {
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
  });

  const left = doc.page.margins.left;
  const width = doc.page.width - doc.page.margins.left - doc.page.margins.right;

  doc.font("Helvetica-Bold").fontSize(18).fillColor("#191A5C").text("Nandini Logistics", left, 48);
  doc.font("Helvetica").fontSize(10).fillColor("#7A80A3").text("Payslip — internal staff");
  doc.moveDown(0.6);
  doc.font("Helvetica-Bold").fontSize(13).fillColor("#22264A").text(monthLabel(input.month));
  doc.moveDown(0.8);

  const row = (label: string, value: string, bold = false) => {
    const y = doc.y;
    doc.font("Helvetica").fontSize(10).fillColor("#5A6080").text(label, left, y, { width: width * 0.5 });
    doc.font(bold ? "Helvetica-Bold" : "Helvetica").fillColor("#22264A")
      .text(value, left + width * 0.5, y, { width: width * 0.5, align: "right" });
    doc.moveDown(0.35);
  };

  row("Employee", `${input.name} (${input.employeeCode})`);
  row("Designation", input.designation ?? "—");
  row("Payable days", input.payableDays === null ? "—" : String(input.payableDays));
  doc.moveDown(0.4);
  doc.moveTo(left, doc.y).lineTo(left + width, doc.y).strokeColor("#E3E7F2").stroke();
  doc.moveDown(0.6);

  row("Gross salary", rupees(input.gross));
  row("Less: advance recovery", rupees(input.advance));
  row("Less: deductions", rupees(input.deductions));
  doc.moveDown(0.3);
  doc.moveTo(left, doc.y).lineTo(left + width, doc.y).strokeColor("#E3E7F2").stroke();
  doc.moveDown(0.5);
  row("Net pay", rupees(input.netPay), true);

  if (input.notes) {
    doc.moveDown(1);
    doc.font("Helvetica").fontSize(9.5).fillColor("#5A6080").text(`Notes: ${input.notes}`, left, doc.y, { width });
  }

  doc.moveDown(2);
  doc.font("Helvetica").fontSize(8.5).fillColor("#7A80A3")
    .text(`Generated by ${input.generatedBy} on ${input.generatedAt.toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" })}. This is a system-generated payslip.`, left, doc.y, { width });

  doc.end();
  return done;
}
