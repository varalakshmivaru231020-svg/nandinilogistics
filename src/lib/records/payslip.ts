import "server-only";

import { prisma } from "@/lib/db";
import { PERM } from "@/lib/permissions/codes";
import type { AuthContext } from "@/lib/rbac/context";
import { monthLabel } from "@/lib/staff/payslip";

import type { RecordAction, RecordView } from "./shared";

/** What may be done to a payslip: delete, which is all the web offers beyond the PDF. */
export function payslipDecisions(p: { id: string; month: string }, can: { remove: boolean }): RecordAction[] {
  if (!can.remove) return [];
  return [{
    key: "delete", label: "Delete payslip", emphasis: "reject",
    action: "staff/payslips/deletePayslip", args: [p.id], remark: "none",
    confirm: `The ${monthLabel(p.month)} payslip and its PDF go. It can be generated again.`,
  }];
}

export async function payslipRecord(ctx: AuthContext, id: string): Promise<RecordView | null> {
  const p = await prisma.payslip.findUnique({
    where: { id },
    include: {
      employee: { select: { name: true, employeeCode: true, designation: { select: { name: true } } } },
      generatedBy: { select: { name: true } },
    },
  });
  if (!p) return null;

  return {
    key: "staff/payslips",
    id: p.id,
    title: `${p.employee.name} · ${monthLabel(p.month)}`,
    subtitle: p.employee.employeeCode,
    pills: [{ label: "Generated", tone: "good" }],
    sections: [
      {
        label: "Payslip",
        fields: [
          { label: "Designation", value: p.employee.designation?.name ?? null },
          { label: "Month", value: monthLabel(p.month) },
          { label: "Payable days", value: p.payableDays },
          { label: "Gross salary", value: Number(p.gross), format: "money" },
          { label: "Advance recovery", value: Number(p.advance), format: "money" },
          { label: "Other deductions", value: Number(p.deductions), format: "money" },
          { label: "Net pay", value: Number(p.netPay), format: "money" },
          { label: "Generated by", value: p.generatedBy.name },
          { label: "Generated", value: p.createdAt.toISOString(), format: "datetime" },
          { label: "Notes", value: p.notes, wide: true },
        ],
      },
    ],
    collections: p.pdfKey
      ? [{
          key: "pdf",
          label: "PDF",
          rows: [{
            id: `pdf:${p.id}`,
            title: `payslip-${p.employee.employeeCode}-${p.month}.pdf`,
            file: { url: `/api/staff/payslips/${p.id}`, name: `payslip-${p.employee.employeeCode}-${p.month}.pdf`, mime: "application/pdf" },
          }],
        }]
      : [],
    actions: payslipDecisions({ id: p.id, month: p.month }, { remove: ctx.has(PERM.staff.payslip.delete) }),
    serverTime: new Date().toISOString(),
  };
}
