/**
 * Writes `docs/WHATSAPP.md` from the event registry.
 *
 * The list of triggers is a thing people ask for and a thing that goes stale,
 * so it is generated rather than typed: `src/lib/whatsapp/events.ts` is the
 * one place an event is described, and this prints it. Run it after changing
 * the registry — `pnpm whatsapp:doc`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");

// Read the registry as text rather than importing it: it is a server module,
// and this script has no Next.js around it.
const source = readFileSync(join(ROOT, "src", "lib", "whatsapp", "events.ts"), "utf8");
const block = source.slice(
  source.indexOf("export const WHATSAPP_EVENTS"),
  source.indexOf("] as const;", source.indexOf("export const WHATSAPP_EVENTS")),
);

const events = [];
for (const chunk of block.split(/\n  \{\n/).slice(1)) {
  const field = (name) => {
    const m = new RegExp(`${name}:\\s*\\n?\\s*"((?:[^"\\\\]|\\\\.)*)"`, "s").exec(chunk);
    return m ? m[1].replace(/\s+/g, " ") : "";
  };
  const variables = /variables:\s*\[([^\]]*)\]/s.exec(chunk);
  events.push({
    key: field("key"),
    label: field("label"),
    module: field("module"),
    audience: field("audience"),
    recipient: field("recipient"),
    fires: field("fires"),
    template: field("template"),
    variables: variables
      ? variables[1]
          .split(",")
          .map((v) => v.trim().replace(/^"|"$/g, ""))
          .filter(Boolean)
      : [],
    button: /button:\s*\{/.test(chunk),
  });
}

if (events.length === 0) throw new Error("No events parsed — has events.ts changed shape?");

const WHERE = {
  APPROVAL_PENDING:
    "`material/indents/actions.ts` (submitted) and `material/purchase-orders/actions.ts` (PM approved → Admin)",
  TASK_OVERDUE: "`src/lib/tasks/overdue-sweep.ts`, from the five-minute cron",
  CHECKLIST_POINT_DENIED: "`tasks/actions.ts` → `reviewChecklistItemAction`, on a FAIL verdict",
  FOLLOWUP_OVERDUE: "`src/lib/sales/lead-service.ts` → `escalateOverdueFollowUps`",
  RECEIPT_BOUNCED: "`sales/receipts/actions.ts` → `bounceReceiptAction`",
  UNIT_HOLD_EXPIRING: "`src/lib/whatsapp/sweeps.ts`, from the five-minute cron",
  PURCHASE_ORDER_ISSUED: "`material/purchase-orders/actions.ts`, on the Admin approval",
  PAYMENT_RECEIPT: "`sales/receipts/actions.ts` → `clearReceiptAction`",
  BOOKING_CONFIRMED: "`sales/bookings/actions.ts` → `createBookingAction`",
};

const L = [];
const A = (line = "") => L.push(line);

A("# WhatsApp");
A();
A("<!-- Generated by `pnpm whatsapp:doc` from src/lib/whatsapp/events.ts. Do not hand-edit the table. -->");
A();
A(`Nine events can send a WhatsApp message. Each one is off until an administrator`);
A("switches it on at **Masters & Users → WhatsApp**, and each needs an approved");
A("template — the words are in [WHATSAPP_TEMPLATES.md](WHATSAPP_TEMPLATES.md).");
A();
A("## The triggers");
A();
A("| # | Event | Fires when | Goes to | Template | Vars |");
A("|---|---|---|---|---|---|");
events.forEach((e, i) => {
  A(
    `| ${i + 1} | **${e.label}**<br>\`${e.key}\` | ${e.fires} | ${e.recipient}${
      e.audience === "staff" ? "" : ` _(${e.audience} — outside the organisation)_`
    } | \`${e.template}\` | ${e.variables.length}${e.button ? " + link" : ""} |`,
  );
});
A();
A("## Where each one is raised");
A();
A("| Event | In the code |");
A("|---|---|");
for (const e of events) A(`| \`${e.key}\` | ${WHERE[e.key] ?? "—"} |`);
A();
A(`## How it travels

1. The business flow calls \`enqueueWhatsApp()\`, which writes one row in
   \`whatsapp_messages\` — or nothing, if the trigger is off. **It never throws**:
   a booking must not fail because a template was renamed.
2. \`POST /api/whatsapp/dispatch\` runs every five minutes from cron. It sweeps
   overdue tasks and lapsing holds — both of which write more rows — and then
   drains the outbox.
3. A refusal about the message itself (400: template not approved, number not on
   WhatsApp) is final. Their outage (5xx, 429) or an unreachable host is tried
   again after 2, then 8, then 32 minutes, four attempts in all.
4. Every message stays as a row, sent or not. The log on the WhatsApp tab is
   that table.

## The connection

**Masters & Users → WhatsApp → Connection.** Nothing lives in an environment
variable, because a token in one needs a deploy to rotate and this one does not
— it is read fresh on every send.

| Field | What it is |
|---|---|
| API url | \`https://graph.facebook.com\` for Meta direct, or a BSP's own base url. A BSP that proxies Meta (BotSyncWA, 360dialog, Gupshup) needs nothing else changed. |
| Version | \`v21.0\` for Meta. A BSP may pin its own. |
| Phone number id | The id of the sending number, not the number. |
| WhatsApp Business Account id | Only to read approved templates back from Meta. A BSP that keeps templates in its own portal has none. |
| Access token | Write-only. The screen is told whether one is set and its last four characters, never the token. |
| Send WhatsApp messages | Off, nothing is sent and nothing is queued. The triggers keep their settings. |

A trigger cannot be switched on unless its template is **approved** at Meta —
otherwise it would queue messages that can never leave.

## Installing the cron

\`\`\`bash
# on the server, once
echo 'WHATSAPP_CRON_SECRET=<a long random string>' >> /var/www/nninfra/app/.env
install -m 644 deploy/nninfra-whatsapp.cron /etc/cron.d/nninfra-whatsapp
pm2 restart nninfra           # so the app reads the new variable
\`\`\`

Without \`WHATSAPP_CRON_SECRET\` the endpoint refuses every call, which is what
an unconfigured host should do. The sweeps then never run — including the
overdue-task notices, which this endpoint is also the only caller of.

## What is deliberately not here

- **Delivery receipts.** Meta's webhook can say *delivered* and *read*;
  \`metaMessageId\` is stored against every sent row so it can be matched later,
  but nothing consumes the webhook yet.
- **Opt-in records.** The three outside events — a vendor's order, a customer's
  receipt and their booking — need the recipient to have agreed beforehand.
  Where that is recorded is not decided.
- **Quiet hours**, and a per-person choice of which events reach them.
`);

writeFileSync(join(ROOT, "docs", "WHATSAPP.md"), L.join("\n"));
console.log(`docs/WHATSAPP.md — ${events.length} triggers`);
